"""
GET /evaluation/latest — serves the most recent evaluation report
generated by scripts/run_evaluation.py, for the dashboard's Results page.

This endpoint reads a JSON file from disk rather than the database
because the evaluation report is a point-in-time artifact of a specific
script run against the held-out set — treating it as a file makes it
obvious that "the numbers" come from a specific, reproducible run, not a
live query that could silently change.
"""

import json
from pathlib import Path

from fastapi import APIRouter, HTTPException

router = APIRouter(prefix="/evaluation", tags=["evaluation"])

_REPORT_PATH = Path(__file__).parent.parent.parent / "data" / "eval" / "latest_report.json"


@router.get("/latest")
def get_latest_evaluation():
    if not _REPORT_PATH.exists():
        raise HTTPException(
            status_code=404,
            detail="No evaluation report found. Run "
            "`python scripts/run_evaluation.py` first.",
        )
    return json.loads(_REPORT_PATH.read_text())
